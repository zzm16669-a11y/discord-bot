def _load_state() -> dict:
    if not os.path.exists(AJR_STATE_FILE):
        return {}
    try:
        with open(AJR_STATE_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError):
        return {}


def _save_state(state: dict) -> None:
    with open(AJR_STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(state, f, ensure_ascii=False, indent=2)


def find_ajr_channel(guild: discord.Guild) -> discord.TextChannel | None:
    target = AJR_CHANNEL_NAME.lower()
    for ch in guild.text_channels:
        if target in ch.name.lower().replace("_", "-"):
            return ch
    return None


def _next_item(guild_state: dict) -> tuple:
    """يسحب العنصر التالي من طابور عشوائي (ما يتكرر نص لين تخلص القائمة)."""
    queue = [i for i in guild_state.get("queue", []) if 0 <= i < len(AJR_ITEMS)]
    if not queue:
        queue = list(range(len(AJR_ITEMS)))
        random.shuffle(queue)
        # نتجنب إن أول عنصر بالدورة الجديدة يكون نفس آخر عنصر انرسل
        last = guild_state.get("last_index")
        if len(queue) > 1 and queue[0] == last:
            queue[0], queue[-1] = queue[-1], queue[0]
    index = queue.pop(0)
    guild_state["queue"] = queue
    guild_state["last_index"] = index
    return AJR_ITEMS[index]


def build_embed(bot, kind: str, text: str, source: str) -> discord.Embed:
    """نفس قالب رسالة AFK: عنوان + وصف + صورة جنب + فوتر، بنفس اللون (blurple)."""
    body = f"﴿ {text} ﴾" if kind == "quran" else text
    embed = discord.Embed(
        title=KIND_TITLES[kind],
        description=f"{body}\n\n**المصدر:** {source}",
        color=discord.Color.blurple(),
    )
    if bot.user is not None:
        embed.set_thumbnail(url=bot.user.display_avatar.url)
    embed.set_footer(text="لا تنسونا من صالح دعائكم 🤍")
    return embed


async def send_ajr(bot, channel: discord.TextChannel, guild_state: dict) -> bool:
    kind, text, source = _next_item(guild_state)
    try:
        await channel.send(embed=build_embed(bot, kind, text, source),
                           allowed_mentions=discord.AllowedMentions.none())
        return True
    except (discord.Forbidden, discord.HTTPException) as e:
        print(f"[Ajr] ما قدرت أرسل بروم {channel.name}: {e}")
        return False


def setup_ajr(bot) -> None:
    @tasks.loop(minutes=10)
    async def ajr_loop():
        state = _load_state()
        now = datetime.now(timezone.utc)
        changed = False
        for guild in bot.guilds:
            channel = find_ajr_channel(guild)
            if channel is None:
                continue
            gs = state.setdefault(str(guild.id), {})
            last_iso = gs.get("last_sent")
            if last_iso:
                try:
                    if now - datetime.fromisoformat(last_iso) < AJR_INTERVAL:
                        continue
                except ValueError:
                    pass
            if await send_ajr(bot, channel, gs):
                gs["last_sent"] = now.isoformat()
            changed = True
        if changed:
            _save_state(state)

    @ajr_loop.before_loop
    async def _before_ajr_loop():
        await bot.wait_until_ready()

    @bot.listen("on_ready")
    async def _start_ajr_loop():
        if not ajr_loop.is_running():
            ajr_loop.start()
